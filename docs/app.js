const stepLabels = ["Objetivo", "Inmueble", "Financiación", "Titulares", "Economía", "Contacto"];
let currentBrand = "clarahipoteca";
let step = 1;

const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => Array.from(document.querySelectorAll(sel));

function setText(sel, value) {
  $$(sel).forEach((el) => {
    el.textContent = value;
  });
}

function renderBrand(key) {
  currentBrand = key;
  const brand = brands[key];
  const c = brand.content;

  document.documentElement.dataset.theme = brand.theme;
  document.title = `${c.brand_name} · Demo landing hipotecaria`;

  $$(".switch button").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.brand === key ? "true" : "false");
  });

  setText("[data-bind='brand_name']", c.brand_name);
  setText("[data-bind='brand_tagline']", c.brand_tagline);
  setText("[data-bind='hero_headline']", c.hero_headline);
  setText("[data-bind='hero_subheadline']", c.hero_subheadline);
  setText("[data-bind='hero_cta']", c.hero_cta);
  setText("[data-bind='value_title']", c.value_title);
  setText("[data-bind='value_body']", c.value_body);
  setText("[data-bind='benefits_title']", c.benefits_title);
  setText("[data-bind='process_title']", c.process_title);
  setText("[data-bind='testimonials_title']", c.testimonials_title);
  setText("[data-bind='faq_title']", c.faq_title);
  setText("[data-bind='footer_legal']", c.footer_legal);
  setText("[data-bind='cta_nav']", brand.ctaNav);
  setText("[data-bind='form_title']", brand.formTitle);
  setText("[data-bind='form_lead']", brand.formLead);
  setText("[data-bind='currency']", brand.currency);

  const hero = $("#hero-image");
  if (hero) {
    hero.src = c.hero_image_url;
    hero.alt = c.hero_image_alt;
  }

  const benefits = $("#benefits");
  benefits.innerHTML = c.benefits_items
    .map(
      (item) => `
      <article class="benefit">
        <h3>${item.title}</h3>
        <p>${item.body}</p>
      </article>`
    )
    .join("");

  const steps = $("#process-steps");
  steps.innerHTML = c.process_steps
    .map(
      (item, index) => `
      <li class="step">
        <p class="step-num">${String(index + 1).padStart(2, "0")}</p>
        <h3>${item.title}</h3>
        <p>${item.body}</p>
      </li>`
    )
    .join("");

  const quotes = $("#testimonials");
  quotes.innerHTML = c.testimonials_items
    .map(
      (item) => `
      <blockquote>
        <p>“${item.quote}”</p>
        <footer>
          <strong>${item.name}</strong>
          <span>${item.role}</span>
        </footer>
      </blockquote>`
    )
    .join("");

  const faq = $("#faq");
  faq.innerHTML = c.faq_items
    .map(
      (item) => `
      <details>
        <summary><span>${item.q}</span><span>+</span></summary>
        <p>${item.a}</p>
      </details>`
    )
    .join("");

  const province = $("#province");
  province.innerHTML =
    `<option value="">Selecciona provincia</option>` +
    brand.provinces.map((p) => `<option value="${p}">${p}</option>`).join("");

  $("#phone").placeholder = brand.phonePlaceholder;

  localStorage.setItem("demo_brand", key);
  step = 1;
  showStep();
  $("#form-success").classList.remove("show");
  $("#form-wizard").hidden = false;
}

function showStep() {
  $$(".step-panel").forEach((panel) => {
    panel.hidden = Number(panel.dataset.step) !== step;
  });

  $("#step-label").textContent = `Paso ${step} de 6 · ${stepLabels[step - 1]}`;
  $("#step-percent").textContent = `${Math.round((step / 6) * 100)}%`;
  $("#progress-bar").style.width = `${(step / 6) * 100}%`;
  $("#btn-prev").hidden = step === 1;
  $("#btn-next").textContent = step === 6 ? "Enviar solicitud" : "Continuar";
}

function nextStep() {
  if (step < 6) {
    step += 1;
    showStep();
    return;
  }

  $("#form-wizard").hidden = true;
  $("#form-success").classList.add("show");
}

function prevStep() {
  if (step > 1) {
    step -= 1;
    showStep();
  }
}

document.addEventListener("DOMContentLoaded", () => {
  $$(".switch button").forEach((btn) => {
    btn.addEventListener("click", () => renderBrand(btn.dataset.brand));
  });

  $("#btn-next").addEventListener("click", (e) => {
    e.preventDefault();
    nextStep();
  });

  $("#btn-prev").addEventListener("click", (e) => {
    e.preventDefault();
    prevStep();
  });

  const params = new URLSearchParams(window.location.search);
  const fromQuery = [params.get("demo"), params.get("marca"), params.get("brand")]
    .map((value) => (value || "").toLowerCase().trim())
    .find((value) => Boolean(brands[value]));

  // La URL manda siempre; si no hay parámetro, usa la última marca o Clarahipoteca.
  const saved = localStorage.getItem("demo_brand");
  const initial = fromQuery || (brands[saved] ? saved : "clarahipoteca");
  renderBrand(initial);
});
